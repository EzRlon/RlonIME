def main() -> int:
    terms: list[dict] = []
    seen: set[str] = set()
    for zh, en, cat, var in _T:
        if zh in seen:
            print(f"[WARN] 生成器内重复: {zh}", file=sys.stderr)
            continue
        seen.add(zh)
        item: dict = {
            "zh": zh, "en": en, "brief": cat,
            "scene": "", "software": [], "scene_tags": [],
            "standard": "", "var_en": list(var),
            "freq": _CAT_FREQ[cat],
        }
        # 数字/字母开头的牌号词：显式给 CJK 部分的拼音（保证键盘可输入）
        cjk = re.sub(r"[^\u4e00-\u9fff]", "", zh)
        if cjk and cjk != zh:
            from pypinyin import lazy_pinyin, Style
            item["pinyin"] = "".join(lazy_pinyin(cjk, style=Style.NORMAL))
            item["abbr"] = "".join(
                lazy_pinyin(cjk, style=Style.FIRST_LETTER))
        # 多音字专业读音修正（只改全拼；abbr 由首字母生成，不受读音影响）
        if zh in _PINYIN_FIX:
            item["pinyin"] = _PINYIN_FIX[zh]
        # 备用读音：命中同样走 term_index，等同于「两种打字习惯都认」
        if zh in _ALT_PINYIN:
            item["pinyin_alt"] = list(_ALT_PINYIN[zh])
        terms.append(item)

    # 注：与专业词库同词也照收（v2.3 修正）——共享层意义在于「任何场景都可命中」；
    # 同场景重复由引擎层去重（专业版优先），不会出重复候选。
    data = {
        "name": "工程通用词库",
        "description": "材料 / 表面处理 / 加工工艺 / 制造流程 / 通用件"
                       "—— 全行业共享词汇层（v2.3）",
        "version": "1.1.0",
        "terms": terms,
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")

    from collections import Counter
    cnt = Counter(t["brief"] for t in terms)
    print(f"生成 {OUT.relative_to(ROOT)}：{len(terms)} 条")
    for k, v in cnt.items():
        print(f"  {k}: {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
